export function getSiteById(id: string): HeritageSite | undefined {
  return heritageSites.find(site => site.id === id);
}

export function searchSites(query: string): HeritageSite[] {
  const q = query.toLowerCase().trim();
  if (!q) return heritageSites;
  return heritageSites.filter(site =>
    site.name.toLowerCase().includes(q) ||
    site.city.toLowerCase().includes(q) ||
    site.state.toLowerCase().includes(q) ||
    site.heritageType.toLowerCase().includes(q) ||
    site.description.toLowerCase().includes(q)
  );
}
